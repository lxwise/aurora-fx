package io.aurora.fx.components.translationButton;

/**
 * 平移按钮动画方向枚举
 * <p>
 * 定义鼠标悬停时内容的平移动画方向。
 * </p>
 *
 * @author Aurora-FX
 * @version 1.0
 */
public enum TranslationDirection {

    /** 从底部向顶部平移 */
    BOTTOM_TO_TOP,

    /** 从顶部向底部平移 */
    TOP_TO_BOTTOM,

    /** 从左侧向右侧平移 */
    LEFT_TO_RIGHT,

    /** 从右侧向左侧平移 */
    RIGHT_TO_LEFT
}
